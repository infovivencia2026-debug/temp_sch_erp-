/* Year-end payout: holiday work and unused leave paid out once a year, added
   to one month's payroll as pay adjustments (owner, 2026-10-14).
   Generated by `npm run feature:new` (scripts/feature.mjs) for payroll.year_end_payout; grown by hand. */

/** How a day is priced: gross / 30, CTC / 30, gross over the work pattern's divisor, or a fixed figure a day. */
export type YearEndRate = 'gross_30' | 'ctc_30' | 'pattern' | 'fixed'

export interface YearEndSettings {
  holiday_rate: YearEndRate
  holiday_fixed_paise: number
  /** 0 = no cap. */
  holiday_max_days: number
  leave_rate: YearEndRate
  leave_fixed_paise: number
  leave_max_days: number
  /** Which leave types count: those whose policy rule says encashable, or every paid type. */
  leave_types: 'encashable' | 'paid'
  /** False until migration 0087 reaches this school: the defaults are shown and Save is refused. */
  available: boolean
}

export interface YearEndLeaveType { id: string; code: string; name: string; quota: number; encashable: boolean; is_paid: boolean }

export interface YearEndLeaveTaken { on: string; to: string; days: number; type: string }

export interface YearEndRow {
  employee_id: string
  employee_code: string
  full_name: string
  /** No salary in force for the pay month: no day's pay to price with. */
  no_salary: boolean
  day_pay_paise: number
  leave_quota: number
  leave_taken: number
  leave_taken_dates: YearEndLeaveTaken[]
  leave_unused: number
  /** Days the payout counts after the cap. */
  leave_days: number
  leave_paise: number
  holiday_dates: string[]
  /** Holidays worked typed in by hand on the months of the year (payroll_month_days). */
  holiday_manual: number
  holiday_days: number
  holiday_paise: number
}

export interface YearEndPaid { id: string; at: string; by_name: string; month: number; year: number; people: number; total_paise: number }

export interface YearEndSummary {
  years: { id: string; name: string; starts_on: string; ends_on: string; is_current: boolean }[]
  year: { id: string; name: string; starts_on: string; ends_on: string } | null
  pay_month: number
  pay_year: number
  month_locked: boolean
  /** The monthly run already pays holiday work when this is on (Statutory -> Settings). */
  pay_holidays_worked: boolean
  paid: YearEndPaid | null
  settings: YearEndSettings
  leave_types: YearEndLeaveType[]
  rows: YearEndRow[]
}

export interface YearEndSaveRow {
  employee_id: string
  holiday_days: number
  holiday_paise: number
  leave_days: number
  leave_paise: number
}

export interface YearEndPayoutApi {
  'GET /payroll/year-end': { query: { year_id?: string; month?: number; year?: number }; res: YearEndSummary }
  'PUT /payroll/year-end/settings': { body: Partial<YearEndSettings>; res: { ok: true } }
  'POST /payroll/year-end': { body: { year_id: string; month: number; year: number; rows: YearEndSaveRow[] }; res: { id: string; people: number; total_paise: number } }
  'DELETE /payroll/year-end/{id}': { res: { deleted: true; removed: number } }
}
